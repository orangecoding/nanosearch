/**
 * Small stroke icons used across the UI. They are decorative: every control
 * that shows only an icon carries its own aria-label.
 * @param {{ size?: number, strokeWidth?: number, children: import('react').ReactNode }} props
 */
function Icon({ size = 16, strokeWidth = 2.2, children, ...rest }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  )
}

